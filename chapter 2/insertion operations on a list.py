# Program to perform insertion operations on a list

# Create a list
my_list = [10, 20, 30, 40]

print("Original list:", my_list)

# Insert an element at the beginning
my_list.insert(0, 5)
print("After inserting 5 at beginning:", my_list)

# Insert an element at a specific position
my_list.insert(2, 15)
print("After inserting 15 at position 2:", my_list)

# Insert an element at the end
my_list.append(50)
print("After inserting 50 at end:", my_list)
